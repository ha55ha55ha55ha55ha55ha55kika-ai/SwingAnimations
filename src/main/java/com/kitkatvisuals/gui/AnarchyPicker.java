package com.kitkatvisuals.gui;

/** То, что нужно окну поиска анархии (EventSearchScreen) от HUD-модуля: его используют HUD-модули ивентов. */
public interface AnarchyPicker {
    /** Выбранная анархия (0 = все). */
    int selected();

    void select(int n);

    /** Число ивентов (шахт) по анархиям 1..36; best[n] = лучший ранг редкости (0 нет, 1..4). */
    int[] anarchyCounts(int[] best);

    /** Заголовок окна. */
    String searchTitle();

    /** Подпись у точки на плитке («есть ивент», «есть шахта»). */
    String legend();

    /** Подпись нижней кнопки; считается каждый кадр, поэтому может показывать текущее значение. */
    String filterLabel();

    /** Нажатие нижней кнопки: открыть окно фильтра или переключить значение (окно поиска при этом остаётся). */
    void filterAction();
}
